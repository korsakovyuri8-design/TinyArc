-- Индекс под поиск расхождения между приёмкой и начислением.
--
-- Панель бюро при каждой загрузке ищет принятые работы, за которыми не завелось
-- обязательство. Поиск ограничен окном в тридцать дней, но без индекса по паре
-- «статус + время приёмки» база всё равно обходила бы все тикеты за всю
-- историю, чтобы отобрать свежие: с годом работы это обход архива на каждое
-- открытие главной страницы панели.
CREATE INDEX "Ticket_status_acceptedAt_idx" ON "Ticket" ("status", "acceptedAt");
