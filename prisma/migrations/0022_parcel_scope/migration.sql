-- Участок становится четвёртым уровнем области нормы.
--
-- Область правила была страна → муниципалитет → зона, и на этом кончалась. В
-- Черногории на этом кончаться нельзя: орган выдаёт условия не на зону, а на
-- локацию. УТУ называет предельные заузетость, изграђеност и спратност для
-- конкретной парцелы и действует, пока действует план, на котором выдан.
--
-- Значит зональное правило — это прогноз («так обычно бывает в этой зоне»), а
-- УТУ — факт по этому проекту. Заведено уровнем области, а не отдельным полем
-- перекрытия: перекрытие означало бы вторую механику разрешения конфликтов
-- рядом с уже работающей, и сделало бы факт исключением из прогноза. Правило
-- «уже — сильнее» просто продолжено на шаг.
--
-- Оба поля пустые по умолчанию: ни одна существующая строка не меняет смысла,
-- а правило без парцелы остаётся ровно тем, чем было.
ALTER TABLE "ComplianceRule" ADD COLUMN "parcel" TEXT;
ALTER TABLE "Project" ADD COLUMN "parcel" TEXT;

-- Выборка правил всегда идёт по области целиком, и парцела — её последний
-- уровень. Прежний индекс кончался зоной, то есть на самом узком уровне
-- проверка возвращалась к чтению всех правил муниципалитета.
DROP INDEX IF EXISTS "ComplianceRule_jurisdiction_municipality_zone_idx";
CREATE INDEX "ComplianceRule_jurisdiction_municipality_zone_parcel_idx"
  ON "ComplianceRule" ("jurisdiction", "municipality", "zone", "parcel");
