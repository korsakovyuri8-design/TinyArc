-- Умолчание доступа специалиста становится закрытым.
--
-- Стояло `founding`: каждый заведённый человек получал бесплатный доступ, и
-- решение о цене продукта принимала строка схемы — невидимая из панели и
-- кончающаяся только выкладкой. Кому доступ открыт, теперь решает настройка
-- пилота (`pilot_free_access_until`), и оба пути заведения — заявка и импорт
-- базы — спрашивают её явно.
--
-- Уже заведённых это не трогает: смена умолчания не переписывает строки.
-- Истёкший пилот никого не выкидывает из отбора — иначе одна настройка сняла
-- бы с живых проектов целые команды, а замена выпавшему не нашлась бы по тому
-- же гейту.
ALTER TABLE "Specialist" ALTER COLUMN "subscription" SET DEFAULT 'none';
