import type { NextConfig } from 'next'

import { MAX_FILE_BYTES } from './src/lib/storage/limits'

/**
 * Заголовки безопасности на каждом ответе.
 *
 * Их не было вовсе: кабинет заказчика можно было вставить в чужой iframe и
 * снять с него нажатия, браузеру разрешалось угадывать тип загруженного файла
 * вместо объявленного, а адрес проекта уезжал в Referer на любую внешнюю
 * ссылку — вместе с ключом в пути, если он там окажется.
 *
 * Полноценной CSP здесь нет намеренно. Next подставляет свои встроенные
 * скрипты, и правило `script-src` без nonce ломает страницы, а nonce нужен
 * proxy, который был удалён вместе с языковой механикой. Ставить CSP с
 * `unsafe-inline` значит записать в конфигурацию, что защита есть, а её нет.
 * `frame-ancestors` при этом взят отдельной строкой: он единственный из CSP,
 * который работает без разбора скриптов.
 */
/**
 * Виден ли стенд поисковикам.
 *
 * Закрыт по умолчанию, и это решение того же рода, что боевой запуск в
 * блюпринте: ошибиться в сторону невидимости дешевле. Первая выкладка идёт на
 * канонический адрес продукта — тот, который потом дают заказчикам, — и
 * попадает в индекс бюро без единого специалиста, с пустой готовностью по всем
 * странам. Выпасть из выдачи потом занимает недели, а объяснять первому
 * клиенту, почему по имени бюро находится заглушка, придётся сразу.
 *
 * Открывается явно, одной переменной, когда показывать уже есть что.
 */
const INDEXABLE = process.env.BUREAU_INDEXABLE === 'yes'

const SECURITY_HEADERS = [
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'X-Frame-Options', value: 'DENY' },
  { key: 'Content-Security-Policy', value: "frame-ancestors 'none'" },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  // Камера, микрофон и геопозиция продукту не нужны — значит, и разрешать их
  // нечему: запрос от встроенного скрипта не должен даже показывать окно.
  { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
  /*
   * HSTS: домен продукта работает только по HTTPS, сертификат выпускает
   * Render. Год и поддомены — обычные значения; preload не заявляем, потому
   * что это односторонняя дорога, и решать её должен владелец домена.
   */
  { key: 'Strict-Transport-Security', value: 'max-age=31536000; includeSubDomains' },
  /*
   * Заголовок, а не только robots.txt: файл — просьба к добросовестному
   * обходчику, заголовок снимает страницу и с тех, кто пришёл по прямой ссылке
   * из письма или чужого поста, минуя корень.
   */
  ...(INDEXABLE ? [] : [{ key: 'X-Robots-Tag', value: 'noindex, nofollow' }]),
]

/*
 * Запас поверх потолка на файл.
 *
 * Предел платформы считает весь запрос целиком, а не файл: multipart добавляет
 * границы частей, заголовки и имена полей. Мегабайта на это хватает с большим
 * запасом — но без него файл ровно в потолок упирался бы в предел, будучи
 * законным.
 */
const MULTIPART_OVERHEAD = 1024 * 1024

const nextConfig: NextConfig = {
  typedRoutes: false,
  /*
   * Потолок на тело серверного действия.
   *
   * По умолчанию платформа режет его на мегабайте, и это не теория: поле
   * загрузки обещает пятьдесят, а на стенде файл в два мегабайта отдавал
   * пятисотку и экран ошибки — специалисту, который ничего не нарушил.
   * Полмегабайта при этом проходили. То есть проверка размера в коде вообще
   * не работала: до неё не доходило.
   *
   * Значение выводится из самого потолка, а не пишется числом рядом: два
   * числа в разных файлах однажды разъезжаются, и разъехавшись, дают ровно
   * ту же пятисотку. Связь сторожит тест.
   *
   * Тело серверного действия платформа держит в памяти целиком, поэтому
   * потолок здесь — это ещё и потолок расхода: несколько одновременных
   * загрузок по пятьдесят мегабайт инстанс на 512 МБ не переживёт. Понижать
   * надо MAX_FILE_BYTES — здесь оно подтянется само.
   */
  experimental: {
    serverActions: {
      bodySizeLimit: MAX_FILE_BYTES + MULTIPART_OVERHEAD,
    },
  },
  // Драйверы баз нативные и/или тянут свои файлы: бандлить их нельзя, они
  // подгружаются из node_modules во время работы.
  serverExternalPackages: [
    'better-sqlite3',
    'pg',
    '@prisma/adapter-better-sqlite3',
    '@prisma/adapter-pg',
  ],
  async headers() {
    return [
      { source: '/:path*', headers: SECURITY_HEADERS },
      /*
       * Сервис-воркер — особый файл, и особые заголовки у него по делу.
       *
       * Он живёт на устройстве до тех пор, пока браузер не увидит новую
       * версию. Закэшированный воркер — это старая логика, которую нечем
       * заменить: он же и решает, что отдавать. Поэтому no-store.
       *
       * Своя CSP здесь возможна там, где на страницах невозможна: у воркера
       * нет встроенных скриптов, и запретить ему всё, кроме своего источника,
       * ничего не ломает.
       */
      {
        source: '/sw.js',
        headers: [
          { key: 'Content-Type', value: 'application/javascript; charset=utf-8' },
          { key: 'Cache-Control', value: 'no-cache, no-store, must-revalidate' },
          { key: 'Content-Security-Policy', value: "default-src 'self'; script-src 'self'" },
        ],
      },
    ]
  },
}

export default nextConfig
