#!/bin/sh
# Убирает длинные тире из видимых текстов сайта.
#
# Почему скриптом, а не готовыми файлами: правка затрагивает сорок файлов, и
# передавать их по одному дольше, чем выполнить одну команду. Плюс скрипт
# остаётся в репозитории: если тире заведётся снова, он прогоняется повторно.
#
# Что делает:
#   "</strong> — "  ->  "</strong>: "   после выделенного термина
#   " — "           ->  ", "            разделитель между частями фразы
#   "—"             ->  ""              остатки без пробелов
#
# Панель бюро (/ops) не трогается: это внутренний инструмент, его читает
# только Юрий, и менять там пунктуацию смысла нет.
#
# Запуск из корня проекта:  sh scripts/no-emdash.sh

set -e

FILES=$(find src/app src/components -name '*.tsx' ! -path '*/ops/*')

for f in $FILES; do
  # Порядок важен. Сначала тире после выделенного термина: там оно держало
  # двоеточие, и запятая на его месте дала бы «Качество, для специалиста без
  # истории это рейтинг» — сращение двух предложений.
  sed -i 's|</strong> — |</strong>: |g' "$f"
  # Затем обычный разделитель между частями фразы.
  sed -i 's/ — /, /g' "$f"
  # И остатки: тире без пробелов, если такое встретится.
  sed -i 's/—//g' "$f"
done

echo "Готово. Проверка:"
LEFT=$(grep -r '—' $FILES 2>/dev/null | wc -l)
echo "осталось вхождений (включая комментарии): $LEFT"
