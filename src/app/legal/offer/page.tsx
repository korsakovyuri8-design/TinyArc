import Link from 'next/link'
import { DOC_STAGE_LABELS } from '@/lib/labels'
import { GOVERNING_LAW, LEGAL_VERSION, company, isIdentified } from '@/lib/legal'
import { JURISDICTIONS, JURISDICTION_NAMES, MAX_STOREYS } from '@/engine/taxonomy'

export const metadata = {
  title: 'Публичная оферта — TinyArc Cloud Bureau',
  description: 'Условия оказания услуг: состав комплекта, цена, оплата по стадиям, ответственность.',
}

/**
 * Публичная оферта.
 *
 * Написана под то, как продукт устроен на самом деле, а не под шаблон из сети:
 * оплата по стадиям вперёд (п.14а), приёмка двумя сторонами (п.12б), команду
 * собирает алгоритм (п.6), продуктовая граница по этажности и странам (п.5).
 * Договор, расходящийся с продуктом, хуже отсутствующего: по нему возникают
 * обязательства, которых система не исполняет.
 */
export default function OfferPage() {
  const details = company()
  const identified = isIdentified(details)

  return (
    <section style={{ paddingTop: 'clamp(40px, 7vw, 72px)', paddingBottom: 80 }}>
      <div className="shell" style={{ maxWidth: 760 }}>
        <span className="eyebrow">Правовые документы</span>
        <h1>Публичная оферта</h1>

        <p className="dim" style={{ marginTop: 12, fontSize: '0.85rem' }}>
          Редакция {LEGAL_VERSION} · применимое право — {GOVERNING_LAW}
        </p>

        <div className="panel panel-accent" style={{ marginTop: 28 }}>
          <div className="label label-accent">Прежде чем читать</div>
          <p className="muted" style={{ marginTop: 12, marginBottom: 0 }}>
            Это рабочая редакция, подготовленная вместе с продуктом и описывающая ровно то,
            как он устроен. Она не заменяет проверку юристом в юрисдикции регистрации и
            подлежит такой проверке до первого платного заказа.
          </p>
        </div>

        {!identified && (
          <div className="panel" style={{ marginTop: 20, borderColor: 'var(--fail)' }}>
            <div className="label" style={{ color: 'var(--fail)' }}>
              Реквизиты не заполнены
            </div>
            <p className="muted" style={{ marginTop: 12, marginBottom: 0 }}>
              Наименование, регистрационный номер и адрес подставляются из настроек
              окружения и сейчас пусты. Пока их нет, оферта договором не является: заключать
              его не с кем. Вымышленные реквизиты здесь не подставляются намеренно.
            </p>
          </div>
        )}

        <Article title="1. Кто оказывает услугу">
          <p>
            Услугу оказывает {details.name || '— наименование не заполнено —'}
            {details.registration && `, регистрационный номер ${details.registration}`}
            {details.taxId && `, налоговый номер ${details.taxId}`}
            {details.address && `, адрес: ${details.address}`} (далее — Бюро).
          </p>
          <p>
            Бюро зарегистрировано в Черногории и действует по праву Черногории. Заказчиком
            может быть лицо из любой страны; право, применимое к договору, от этого не
            меняется.
          </p>
        </Article>

        <Article title="2. Что мы делаем и чего не делаем">
          <p>
            Бюро выпускает проектную документацию силами команды специалистов, собранной
            алгоритмом под конкретный проект, и отвечает перед Заказчиком за результат
            целиком.
          </p>
          <p>Бюро не выполняет и не обещает:</p>
          <ul>
            <li>строительные работы, поставку материалов и технический надзор на площадке;</li>
            <li>
              получение разрешения как гарантированный результат: Бюро готовит и подаёт
              комплект, решение принимает орган;
            </li>
            <li>
              работу за пределами продуктовой границы — здания выше {MAX_STOREYS} этажей и
              зоны стандартного (тяжёлого) регулирования Бюро не берёт;
            </li>
            <li>
              выпуск разрешительной документации вне стран, где у команды есть право
              подписи. Сейчас это {JURISDICTIONS.map((j) => JURISDICTION_NAMES[j]).join(', ')}. Проект вне этого перечня Бюро
              принять не может — не по договорённости, а потому что подписать комплект будет
              некому.
            </li>
          </ul>
        </Article>

        <Article title="3. Состав комплекта по стадиям">
          <p>
            Работа идёт стадиями: {Object.values(DOC_STAGE_LABELS).join(', ').toLowerCase()}.
            Заказчик выбирает целевую стадию в брифе; стадии за ней не заказываются и не
            оплачиваются.
          </p>
          <p>
            Состав задач каждой стадии определяется формой проекта — типологией,
            материальной системой, рельефом, подключением к сетям — и виден Заказчику в
            кабинете проекта до начала работ.
          </p>
        </Article>

        <Article title="4. Цена и порядок оплаты">
          <p>
            Цена стадии рассчитывается автоматически и складывается из площади объекта,
            ставки стадии, множителя типологии и множителя страны, но не ниже
            установленного для стадии минимума. Расчёт показывается Заказчику вместе со
            счётом: он видит не только сумму, но и то, из чего она сложилась.
          </p>
          <p>
            <strong>Стадия оплачивается до начала работ по ней.</strong> Открытие задачи
            означает, что за неё взялся конкретный специалист, и Бюро не вправе начинать
            стадию в долг перед исполнителями.
          </p>
          <p>
            Счёт на очередную стадию выставляется только после того, как Заказчик
            подтвердил предыдущую. Платить вперёд за работу, которую Заказчик ещё не принял,
            не приходится ни разу.
          </p>
          <p>
            Цена, указанная в выставленном счёте, не пересматривается. Изменение расценок
            Бюро действует только на счета, выставленные после изменения.
          </p>
        </Article>

        <Article title="5. Приёмка и подтверждение стадии">
          <p>
            Стадия закрывается двумя действиями. Бюро принимает работу у специалистов — это
            означает «сделано так, как поставлено». Заказчик подтверждает стадию — это
            означает «поставлено было именно то, что заказывалось».
          </p>
          <p>
            Пока подтверждения нет, следующая стадия не начинается. Замечания Заказчика
            принимаются через его канал связи с Бюро и переводятся Бюро в круг правок в
            рамках оплаченной стадии.
          </p>
        </Article>

        <Article title="6. Состав команды">
          <p>
            Команду под проект определяет алгоритм по заявленным и подтверждённым признакам
            специалистов. Ни Заказчик, ни Бюро не назначают конкретных исполнителей: такого
            действия в системе не существует.
          </p>
          <p>
            Выбывшего участника заменяет следующий по расчёту кандидат. Замена не является
            изменением условий договора и не влияет на цену стадии.
          </p>
        </Article>

        <Article title="7. Права на результат">
          <p>
            Материалы, выпущенные по договору и принятые Бюро, принадлежат Заказчику и
            передаются ему в полном объёме по завершении оплаченных стадий.
          </p>
          <p>
            Бюро вправе указывать факт выполнения проекта и обезличенные его характеристики
            (типология, площадь, стадия, страна) в своих материалах. Адрес объекта, имя
            Заказчика и содержание документации при этом не раскрываются без его согласия.
          </p>
        </Article>

        <Article title="8. Ответственность">
          <p>
            Бюро отвечает за соответствие выпущенной документации поставленной задаче и
            требованиям, действующим в стране объекта на момент выпуска стадии.
          </p>
          <p>
            Ответственность Бюро по каждой стадии ограничена суммой, фактически оплаченной
            за эту стадию. Бюро не отвечает за убытки, возникшие из-за сведений об участке,
            предоставленных Заказчиком и оказавшихся недостоверными, а также за изменения
            требований органов после выпуска стадии.
          </p>
        </Article>

        <Article title="9. Отказ от договора и возврат">
          <p>
            Заказчик вправе отказаться от дальнейшей работы в любой момент. Оплаченная
            стадия, работа по которой ещё не начата (ни одна задача не открыта), возвращается
            полностью. По начатой стадии возвращается часть, соответствующая непринятым
            задачам на момент отказа: принятая работа выполнена людьми и оплачена им.
          </p>
          <p>
            Бюро вправе отказаться от проекта, если после брифа выясняется, что он выходит за
            продуктовую границу, — с полным возвратом оплаченного.
          </p>
        </Article>

        <Article title="10. Персональные данные">
          <p>
            Обработка персональных данных описана в{' '}
            <Link href="/legal/privacy">Политике обработки данных</Link>, которая является
            неотъемлемой частью настоящей оферты.
          </p>
        </Article>

        <Article title="11. Применимое право и споры">
          <p>
            К договору применяется право Черногории. Споры, не урегулированные переговорами,
            рассматриваются судом по месту регистрации Бюро.
          </p>
          <p>
            Если Заказчик — потребитель, находящийся в стране, право которой предоставляет
            ему защиту, не отменяемую соглашением сторон, такая защита за ним сохраняется.
          </p>
        </Article>

        <Article title="12. Изменения оферты">
          <p>
            Редакция оферты обозначена датой в начале документа. К уже заключённому договору
            применяется та редакция, которая действовала на момент согласия Заказчика: она
            фиксируется вместе с отметкой времени.
          </p>
        </Article>

        <div className="divider" style={{ marginTop: 44 }} />

        <p className="dim" style={{ fontSize: '0.85rem' }}>
          Вопросы по договору: {details.email || '— адрес не заполнен —'}
        </p>

        <p style={{ marginTop: 24 }}>
          <Link href="/legal/privacy">Политика обработки данных →</Link>
        </p>
      </div>
    </section>
  )
}

function Article({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div style={{ marginTop: 40 }}>
      <h2 style={{ fontSize: '1.15rem' }}>{title}</h2>
      <div className="muted legal-body" style={{ marginTop: 12 }}>
        {children}
      </div>
    </div>
  )
}
