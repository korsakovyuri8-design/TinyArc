import { Link } from '@/components/Link'
import { translator } from '@/lib/i18n'
import { pageMetadata } from '@/lib/i18n/metadata'
import { DOC_STAGE_LABELS } from '@/lib/labels'
import { GOVERNING_LAW, LEGAL_VERSION, company, isIdentified } from '@/lib/legal'
import { JURISDICTIONS, JURISDICTION_NAMES, MAX_STOREYS } from '@/engine/taxonomy'

export const generateMetadata = () =>
  pageMetadata(
    'Публичная оферта',
    'Условия оказания услуг: состав комплекта, цена, оплата по стадиям, ответственность.',
  )

/**
 * Публичная оферта.
 *
 * Написана под то, как продукт устроен на самом деле, а не под шаблон из сети:
 * оплата по стадиям вперёд (п.14а), приёмка двумя сторонами (п.12б), команду
 * собирает алгоритм (п.6), продуктовая граница по этажности и странам (п.5).
 * Договор, расходящийся с продуктом, хуже отсутствующего: по нему возникают
 * обязательства, которых система не исполняет.
 */
export default async function OfferPage() {
  const { locale, t } = await translator()
  const details = company()
  const identified = isIdentified(details)

  return (
    <section style={{ paddingTop: 'clamp(40px, 7vw, 72px)', paddingBottom: 80 }}>
      <div className="shell" style={{ maxWidth: 760 }}>
        <span className="eyebrow">{t('Правовые документы')}</span>
        <h1>{t('Публичная оферта')}</h1>

        <p className="dim" style={{ marginTop: 12, fontSize: '0.85rem' }}>
          {t('Редакция')} {LEGAL_VERSION} · {t('применимое право —')} {t(GOVERNING_LAW)}
        </p>

        <div className="panel panel-accent" style={{ marginTop: 28 }}>
          <div className="label label-accent">{t('Прежде чем читать')}</div>
          <p className="muted" style={{ marginTop: 12, marginBottom: 0 }}>{t('Это рабочая редакция, подготовленная вместе с продуктом и описывающая ровно то, как он устроен. Она не заменяет проверку юристом в юрисдикции регистрации и подлежит такой проверке до первого платного заказа.')}</p>
        </div>

        {!identified && (
          <div className="panel" style={{ marginTop: 20, borderColor: 'var(--fail)' }}>
            <div className="label" style={{ color: 'var(--fail)' }}>{t('Реквизиты не заполнены')}</div>
            <p className="muted" style={{ marginTop: 12, marginBottom: 0 }}>{t('Наименование, регистрационный номер и адрес подставляются из настроек окружения и сейчас пусты. Пока их нет, оферта договором не является: заключать его не с кем. Вымышленные реквизиты здесь не подставляются намеренно.')}</p>
          </div>
        )}

        <Article title={t('1. Кто оказывает услугу')}>
          <p>
            {t('Услугу оказывает')} {details.name || t('— наименование не заполнено —')}
            {details.registration && `, ${t('регистрационный номер')} ${details.registration}`}
            {details.taxId && `, ${t('налоговый номер')} ${details.taxId}`}
            {details.address && `, ${t('адрес:')} ${details.address}`} {t('(далее — Бюро).')}
          </p>
          <p>{t('Бюро зарегистрировано в Черногории и действует по праву Черногории. Заказчиком может быть лицо из любой страны; право, применимое к договору, от этого не меняется.')}</p>
        </Article>

        <Article title={t('2. Что мы делаем и чего не делаем')}>
          <p>{t('Бюро выпускает проектную документацию силами команды специалистов, собранной алгоритмом под конкретный проект, и отвечает перед Заказчиком за результат целиком.')}</p>
          <p>{t('Бюро не выполняет и не обещает:')}</p>
          <ul>
            <li>{t('строительные работы, поставку материалов и технический надзор на площадке;')}</li>
            <li>{t('получение разрешения как гарантированный результат: Бюро готовит и подаёт комплект, решение принимает орган;')}</li>
            <li>
              {t('работу за пределами продуктовой границы — здания выше N этажей и зоны стандартного (тяжёлого) регулирования Бюро не берёт;').replace(
                'N',
                String(MAX_STOREYS),
              )}
            </li>
            <li>
              {t('выпуск разрешительной документации вне стран, где у команды есть право подписи. Сейчас это N. Проект вне этого перечня Бюро принять не может — не по договорённости, а потому что подписать комплект будет некому.').replace(
                'N',
                JURISDICTIONS.map((j) => t(JURISDICTION_NAMES[j])).join(', '),
              )}
            </li>
          </ul>
        </Article>

        <Article title={t('3. Состав комплекта по стадиям')}>
          <p>
            {t('Работа идёт стадиями: N. Заказчик выбирает целевую стадию в брифе; стадии за ней не заказываются и не оплачиваются.').replace(
              'N',
              Object.values(DOC_STAGE_LABELS)
                .map((stage) => t(stage).toLowerCase())
                .join(', '),
            )}
          </p>
          <p>{t('Состав задач каждой стадии определяется формой проекта — типологией, материальной системой, рельефом, подключением к сетям — и виден Заказчику в кабинете проекта до начала работ.')}</p>
        </Article>

        <Article title={t('4. Цена и порядок оплаты')}>
          <p>{t('Цена стадии рассчитывается автоматически и складывается из площади объекта, ставки стадии, множителя типологии и множителя страны, но не ниже установленного для стадии минимума. Расчёт показывается Заказчику вместе со счётом: он видит не только сумму, но и то, из чего она сложилась.')}</p>
          <p>
            <strong>{t('Стадия оплачивается до начала работ по ней.')}</strong>{t('Открытие задачи означает, что за неё взялся конкретный специалист, и Бюро не вправе начинать стадию в долг перед исполнителями.')}</p>
          <p>{t('Счёт на очередную стадию выставляется только после того, как Заказчик подтвердил предыдущую. Платить вперёд за работу, которую Заказчик ещё не принял, не приходится ни разу.')}</p>
          <p>{t('Цена, указанная в выставленном счёте, не пересматривается. Изменение расценок Бюро действует только на счета, выставленные после изменения.')}</p>
        </Article>

        <Article title={t('5. Приёмка и подтверждение стадии')}>
          <p>{t('Стадия закрывается двумя действиями. Бюро принимает работу у специалистов — это означает «сделано так, как поставлено». Заказчик подтверждает стадию — это означает «поставлено было именно то, что заказывалось».')}</p>
          <p>{t('Пока подтверждения нет, следующая стадия не начинается. Замечания Заказчика принимаются через его канал связи с Бюро и переводятся Бюро в круг правок в рамках оплаченной стадии.')}</p>
        </Article>

        <Article title={t('6. Состав команды')}>
          <p>{t('Команду под проект определяет алгоритм по заявленным и подтверждённым признакам специалистов. Ни Заказчик, ни Бюро не назначают конкретных исполнителей: такого действия в системе не существует.')}</p>
          <p>{t('Выбывшего участника заменяет следующий по расчёту кандидат. Замена не является изменением условий договора и не влияет на цену стадии.')}</p>
        </Article>

        <Article title={t('7. Права на результат')}>
          <p>{t('Материалы, выпущенные по договору и принятые Бюро, принадлежат Заказчику и передаются ему в полном объёме по завершении оплаченных стадий.')}</p>
          <p>{t('Бюро вправе указывать факт выполнения проекта и обезличенные его характеристики (типология, площадь, стадия, страна) в своих материалах. Адрес объекта, имя Заказчика и содержание документации при этом не раскрываются без его согласия.')}</p>
        </Article>

        <Article title={t('8. Ответственность')}>
          <p>{t('Бюро отвечает за соответствие выпущенной документации поставленной задаче и требованиям, действующим в стране объекта на момент выпуска стадии.')}</p>
          <p>{t('Ответственность Бюро по каждой стадии ограничена суммой, фактически оплаченной за эту стадию. Бюро не отвечает за убытки, возникшие из-за сведений об участке, предоставленных Заказчиком и оказавшихся недостоверными, а также за изменения требований органов после выпуска стадии.')}</p>
        </Article>

        <Article title={t('9. Отказ от договора и возврат')}>
          <p>{t('Заказчик вправе отказаться от дальнейшей работы в любой момент. Оплаченная стадия, работа по которой ещё не начата (ни одна задача не открыта), возвращается полностью. По начатой стадии возвращается часть, соответствующая непринятым задачам на момент отказа: принятая работа выполнена людьми и оплачена им.')}</p>
          <p>{t('Бюро вправе отказаться от проекта, если после брифа выясняется, что он выходит за продуктовую границу, — с полным возвратом оплаченного.')}</p>
        </Article>

        <Article title={t('10. Персональные данные')}>
          <p>
            {t('Обработка персональных данных описана в')}{' '}
            <Link locale={locale} href="/legal/privacy">
              {t('Политике обработки данных')}
            </Link>
            {t(', которая является неотъемлемой частью настоящей оферты.')}
          </p>
        </Article>

        <Article title={t('11. Применимое право и споры')}>
          <p>{t('К договору применяется право Черногории. Споры, не урегулированные переговорами, рассматриваются судом по месту регистрации Бюро.')}</p>
          <p>{t('Если Заказчик — потребитель, находящийся в стране, право которой предоставляет ему защиту, не отменяемую соглашением сторон, такая защита за ним сохраняется.')}</p>
        </Article>

        <Article title={t('12. Язык оферты')}>
          <p>
            {t('Оферта существует на русском и английском языках, и обе редакции равнозначны.')}
          </p>
          <p>
            {t('При расхождении между ними преимущество имеет та, на языке которой оферта была показана Заказчику в момент принятия. Язык принятия фиксируется вместе с отметкой о согласии. Правило выбрано так намеренно: связывать человека редакцией, которой он не читал, нечестно, а «русская редакция главная, потому что мы её писали» — именно это и означало бы.')}
          </p>
        </Article>

        <Article title={t('13. Изменения оферты')}>
          <p>{t('Редакция оферты обозначена датой в начале документа. К уже заключённому договору применяется та редакция, которая действовала на момент согласия Заказчика: она фиксируется вместе с отметкой времени.')}</p>
        </Article>

        <div className="divider" style={{ marginTop: 44 }} />

        <p className="dim" style={{ fontSize: '0.85rem' }}>
          {t('Вопросы по договору:')} {details.email || t('— адрес не заполнен —')}
        </p>

        <p style={{ marginTop: 24 }}>
          <Link locale={locale} href="/legal/privacy">{t('Политика обработки данных →')}</Link>
        </p>
      </div>
    </section>
  )
}

function Article({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <div style={{ marginTop: 40 }}>
      <h2 style={{ fontSize: '1.15rem' }}>{title}</h2>
      <div className="muted legal-body" style={{ marginTop: 12 }}>
        {children}
      </div>
    </div>
  )
}
