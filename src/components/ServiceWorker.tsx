'use client'

import { useEffect } from 'react'

/**
 * Регистрация сервис-воркера.
 *
 * Клиентский компонент без разметки: ставится в макет один раз и ничего не
 * рисует. Регистрация нужна затем, чтобы продукт можно было установить на
 * телефон, — без воркера браузер предлагать установку не станет.
 *
 * Ошибка регистрации гасится молча и намеренно. Воркер — это удобство
 * (значок на экране и внятный ответ без сети), а не часть работы продукта:
 * упавшая регистрация не должна ничего сообщать человеку, который пришёл
 * заполнять бриф.
 */
export function ServiceWorker() {
  useEffect(() => {
    if (!('serviceWorker' in navigator)) return

    navigator.serviceWorker.register('/sw.js').catch(() => undefined)
  }, [])

  return null
}
