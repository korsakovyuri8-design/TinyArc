/**
 * Политика пилота.
 *
 * Проверяется решение, а не хранение: до какого дня доступ бесплатный и что
 * происходит на самой границе. Момент истечения прогоном не поймать — пилот,
 * кончающийся ровно сейчас, на стенде не воспроизводится, — а ошибка здесь
 * стоит либо лишнего дня раздачи, либо отказа тому, кто пришёл в последний
 * день пилота.
 */

import { describe, expect, it } from 'vitest'
import { accessOnPilot } from './settings'

const now = new Date('2026-06-01T12:00:00.000Z')

describe('какой доступ получает новый специалист', () => {
  it('пока пилот идёт — открытый', () => {
    expect(accessOnPilot(new Date('2026-12-31T23:59:59.000Z'), now)).toBe('founding')
  })

  it('после пилота — закрытый: открывает бюро руками', () => {
    expect(accessOnPilot(new Date('2026-05-31T23:59:59.000Z'), now)).toBe('none')
  })

  /*
   * Настройки нет — значит бесплатного доступа никто не объявлял. Умолчание
   * закрытое намеренно: ошибка в эту сторону видна человеку сразу и лечится
   * одним нажатием, а обратная раздаёт продукт молча и навсегда.
   */
  it('без настройки — закрытый', () => {
    expect(accessOnPilot(null, now)).toBe('none')
  })

  it('на самой границе пилот уже кончился', () => {
    expect(accessOnPilot(new Date(now), now)).toBe('none')
  })

  it('за миллисекунду до границы — ещё идёт', () => {
    expect(accessOnPilot(new Date(now.getTime() + 1), now)).toBe('founding')
  })
})
