/**
 * Подстановка значений во фразу словаря.
 *
 * Появилась после ошибки, которую стоит назвать. Сначала местом подстановки
 * была одиночная заглавная буква — `'Счёт за стадию «S» — P'` и цепочка
 * `.replace('S', …).replace('P', …)`. По-русски это работало; в английском
 * переводе первая же `A` нашлась в слове «An», и письмо ушло со строкой
 * «15548n invoice has been issued for the “EURoncept” stage».
 *
 * Имя в фигурных скобках не встречается в обычном тексте ни на одном языке, и
 * порядок подстановок перестаёт что-либо значить. Незаполненное место остаётся
 * видимым — `{amount}` посреди письма заметен, в отличие от пустоты.
 */

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in values ? String(values[name]) : whole,
  )
}
