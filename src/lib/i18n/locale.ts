/**
 * Язык интерфейса.
 *
 * Продукт написан по-русски, а заказчик может быть откуда угодно (п.13а):
 * участок в Черногории покупают из Лондона и из Дубая. Поэтому английский —
 * не «локализация когда-нибудь», а условие, при котором человек вообще дойдёт
 * до брифа.
 *
 * Устройство выбрано под то, что уже есть, а не под учебник.
 *
 * Русский живёт по прежним адресам, английский — с приставкой `/en`.
 * Приставку снимает proxy и кладёт язык в заголовок; страницы при этом
 * не переезжают никуда, и ни один существующий адрес не меняется. Обратное
 * решение — перенести двадцать две страницы под сегмент `[locale]` — стоило бы
 * правки каждой ссылки в продукте ради того же результата.
 *
 * Отдельные адреса, а не одна страница на два языка, выбраны намеренно.
 * Язык в cookie означает, что поисковый робот и человек по присланной ссылке
 * видят русский, что бы ни выбрал отправитель. Для продукта, который ищут из
 * другой страны, это и есть отсутствие английского.
 */

export const LOCALES = ['ru', 'en'] as const
export type Locale = (typeof LOCALES)[number]

/** Язык по умолчанию. Живёт без приставки: адреса продукта не меняются. */
export const DEFAULT_LOCALE: Locale = 'ru'

/** Заголовок, которым proxy передаёт язык странице. */
export const LOCALE_HEADER = 'x-bureau-locale'

/**
 * Заголовок с путём без приставки языка.
 *
 * Нужен переключателю: чтобы предложить эту же страницу на другом языке, надо
 * знать, какая это страница. Next не отдаёт путь серверному компоненту, а
 * proxy его и так разобрал.
 */
export const PATH_HEADER = 'x-bureau-path'

export function isLocale(value: string | undefined | null): value is Locale {
  return LOCALES.includes(value as Locale)
}

/**
 * Разбор пути: язык и путь без приставки.
 *
 * `/en/brief` → en и `/brief`. `/brief` → ru и `/brief`. Отдельно `/en` без
 * хвоста — это главная по-английски, а не пустой путь.
 */
export function splitLocale(pathname: string): { locale: Locale; rest: string } {
  const [, first, ...tail] = pathname.split('/')

  if (isLocale(first) && first !== DEFAULT_LOCALE) {
    return { locale: first, rest: `/${tail.join('/')}`.replace(/\/$/, '') || '/' }
  }

  return { locale: DEFAULT_LOCALE, rest: pathname }
}

/**
 * Адрес с приставкой языка.
 *
 * Русский без приставки — так адреса продукта остаются прежними, а не
 * превращаются в `/ru/brief` с редиректом со старых.
 */
export function localePath(path: string, locale: Locale): string {
  if (locale === DEFAULT_LOCALE) return path
  if (path === '/') return `/${locale}`

  return `/${locale}${path}`
}

/**
 * Язык, который просит браузер.
 *
 * Разбирается грубо и намеренно: нас интересует только первый понятный нам
 * язык, а веса `q` при двух вариантах ничего не решают. Русский по умолчанию,
 * потому что непонятый заголовок — это не повод показывать английский тому,
 * кто его не просил.
 */
export function preferredLocale(acceptLanguage: string | null): Locale {
  if (!acceptLanguage) return DEFAULT_LOCALE

  for (const part of acceptLanguage.split(',')) {
    const tag = part.split(';')[0]?.trim().toLowerCase().split('-')[0]
    if (isLocale(tag)) return tag
  }

  /*
   * Незнакомый язык — английский, а не русский.
   *
   * Человек, чей браузер просит немецкий, с большей вероятностью прочтёт
   * английский, чем русский. Русский остаётся тем, кто его попросил, и тем,
   * кто пришёл по прямой ссылке без приставки.
   */
  return 'en'
}
