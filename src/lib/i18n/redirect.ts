import { currentLocale } from './index'
import { localePath } from './locale'

/**
 * Адрес перехода на языке текущей страницы.
 *
 * Возвращает строку, а не делает переход сам. Обёртка над `redirect()` теряла
 * бы главное его свойство: TypeScript знает, что `redirect` не возвращается, и
 * дальше по функции код считается недостижимым. Через `await` это знание
 * пропадает, и компилятор начинает требовать возврат там, где его быть не
 * может.
 *
 * Нужна потому, что обычный `redirect('/project')` уводит человека, читавшего
 * английскую версию, на русскую — в самый неудачный момент: он только что ввёл
 * ключ и ждёт свой кабинет. Язык меняется без единого его действия.
 */
export async function localeHref(path: string): Promise<string> {
  return localePath(path, await currentLocale())
}
