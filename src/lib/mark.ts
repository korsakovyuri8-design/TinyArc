/**
 * Геометрия знака бюро. Один источник на шапку, значок и печатные начертания.
 *
 * Знак — квадратная печать, через которую наискось проходит золотой штрих,
 * срезая два угла. Печать потому, что бюро существует ровно постольку,
 * поскольку имеет право подписи: без него проект не берётся вовсе (п.5).
 * Штрих — тот самый слэш из `TinyArc/Bureau`, единственное золотое пятно во
 * всей системе, и золото по правилу редкое.
 *
 * Штрих идёт строго по диагонали квадрата. Иначе два среза выходят неравными,
 * и знак читается как ошибка совмещения, а не как замысел.
 *
 * Числа живут здесь, а не в разметке, потому что набранные руками они уже
 * разошлись: полоса реза в шапке отличалась от полосы в значке на шестнадцать
 * единиц, и на глаз это незаметно ровно до того дня, когда знак поставят
 * рядом сам с собой. Это то же правило, по которому предел тела запроса
 * считается из потолка на файл, а не пишется числом рядом.
 */

/** Сторона холста. Все числа ниже — в этих единицах. */
export const CANVAS = 512

/** Квадрат печати: от и до. */
const LEFT = 128
const RIGHT = 384

/** Насколько штрих выходит за срезанный угол. */
const OVER = 44

/** Насколько полоса реза длиннее самого штриха — чтобы уйти за холст. */
const BEYOND = 44

export type Weights = {
  /** Толщина рамки печати. */
  stroke: number
  /** Ширина штриха по горизонтали. */
  width: number
  /** Зазор между штрихом и срезом рамки, по горизонтали. */
  gap: number
}

/**
 * Начертаний два, и это не украшение.
 *
 * На шестнадцати пикселях рамка основного начертания даёт полпикселя и
 * пропадает — остаётся косая без печати, то есть другой знак. Мелкий кегль
 * нарисован толще ровно настолько, чтобы силуэт дожил до значка вкладки.
 */
export const MASTER: Weights = { stroke: 16, width: 56, gap: 12 }
export const SMALL: Weights = { stroke: 30, width: 68, gap: 14 }

/** Параллелограмм с горизонтальными торцами вдоль диагонали квадрата. */
function diagonal(width: number, beyond: number): string {
  const half = width / 2
  const lowX = LEFT - OVER - beyond
  const lowY = RIGHT + OVER + beyond
  const highX = RIGHT + OVER + beyond
  const highY = LEFT - OVER - beyond

  return [
    `${lowX - half},${lowY}`,
    `${lowX + half},${lowY}`,
    `${highX + half},${highY}`,
    `${highX - half},${highY}`,
  ].join(' ')
}

/** Сам штрих. */
export function bar({ width }: Weights): string {
  return diagonal(width, 0)
}

/** Полоса, которой штрих вырезает из рамки два угла вместе с зазором. */
export function band({ width, gap }: Weights): string {
  return diagonal(width + gap * 2, BEYOND)
}

/** Квадрат печати — прямоугольником, чтобы его можно было обвести штрихом. */
export const SEAL = { x: LEFT, y: LEFT, size: RIGHT - LEFT }
