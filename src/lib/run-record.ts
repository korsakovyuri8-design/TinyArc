/**
 * Что из прогона сохраняется в записях.
 *
 * Отдельным модулем без единого обращения к базе: это правило, а не работа с
 * ней, и проверять его надо без поднятого клиента. Модуль, тянущий за собой
 * базу, тянет её и в тест — а тест, которому нужна база, перестаёт быть
 * модульным.
 */

import type { Assembly, ScoredCandidate } from '@/engine/types'

/**
 * Сколько кандидатов на роль остаётся в разборе прогона.
 *
 * Разбор нужен двум читателям, и обоим — ранжированные, а не все подряд.
 * Заказчик и бюро смотрят разбор по тем, кто вошёл в команду; замена ищет
 * следующего по рангу из того же прогона (п.10а). Ни один из них не читает
 * тех, кто не прошёл гейт: их число и так записано на прогоне — сколько было
 * в пуле и сколько выжило, — а роль, которую нечем закрыть, названа отдельно.
 *
 * Прежде писались все: пул на роли. При сотне человек это четыре с половиной
 * сотни строк на бриф, при тысяче — четыре с половиной тысячи, при пяти —
 * сорок тысяч, и записывались они внутри одной транзакции. Замерено на живом
 * Postgres: при тысяче сборка занимала пять секунд и упиралась в предел
 * транзакции, при пяти тысячах отказывала совсем. То есть бриф перестал бы
 * приниматься ровно в тот момент, когда пул наберётся, — а продукт растёт
 * пулом.
 *
 * Двадцать четыре — втрое больше, чем движок вообще взвешивает на роль
 * (восемь). Глубже двадцати четвёртого места замена не уходила никогда: это
 * значило бы, что с проекта ушли двадцать три человека подряд.
 */
export const CANDIDATES_STORED = 24

/** Ключ роли: дисциплина вместе с требуемыми специализациями и режимом. */
function roleKey(candidate: ScoredCandidate): string {
  return `${candidate.role.discipline}|${candidate.role.mode}|${[...candidate.role.specializations].sort().join('+')}`
}

/**
 * Что из прогона попадает в записи.
 *
 * Прошедшие гейт, по рангу, не больше `CANDIDATES_STORED` на роль — и вдобавок
 * все, кто вошёл в команду. Последнее выглядит лишним (состав набирается из
 * первых восьми), но стоит здесь намеренно: разбор для члена команды ищется в
 * этом списке, и человек, которого в нём не оказалось, показался бы заказчику
 * строкой без объяснения.
 */
export function forRecord(assembly: Assembly): ScoredCandidate[] {
  const chosen = new Set(assembly.team.map((m) => `${m.specialist.id}|${m.discipline}`))
  const perRole = new Map<string, number>()
  const kept: ScoredCandidate[] = []

  for (const candidate of [...assembly.candidates].sort((a, b) => a.rank - b.rank)) {
    const isChosen = chosen.has(`${candidate.specialist.id}|${candidate.discipline}`)

    if (!candidate.passed && !isChosen) continue

    const key = roleKey(candidate)
    const already = perRole.get(key) ?? 0

    if (already >= CANDIDATES_STORED && !isChosen) continue

    perRole.set(key, already + 1)
    kept.push(candidate)
  }

  return kept
}
