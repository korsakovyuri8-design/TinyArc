/**
 * Потолки на свободный текст.
 *
 * Ни у одного текстового поля их не было. Держалось это на случайности:
 * платформа резала тело серверного действия на мегабайте, и длиннее в базу
 * ничего не попадало. Предел поднят до пятидесяти мегабайт ради чертежей — и
 * вместе с ним поднялся потолок у каждого поля, включая комментарий.
 *
 * Комментарий в сорок мегабайт — это не «некрасивая строка в базе». Он
 * читается на каждом открытии тикета всеми, кто к нему допущен, едет в письмо
 * и попадает в архив, который бюро обязано отдать заказчику. Один такой
 * комментарий делает задачу неоткрываемой, а сто — неоткрываемой панель.
 *
 * Потолок стоит в сервисах, а не в разборе формы: сервисы — единственный путь
 * к записи, а серверное действие достижимо прямым запросом и без формы.
 *
 * Текст не обрезается молча. Обрезанный комментарий выглядит как отправленный
 * целиком, и человек узнаёт о потере тогда, когда её уже не восстановить:
 * набранное в поле браузер к тому моменту забыл.
 */

/**
 * Значения выбраны по тому, что в поле пишут, а не по красоте числа.
 *
 * Заголовок и имя файла — строка. Примечание к деньгам — строка с
 * пояснением. Комментарий, возврат на круг, вопрос бюро — абзац-другой.
 * Постановка задачи — самое длинное, что пишет бюро руками.
 */
export const TEXT_MAX = {
  /** Заголовок запроса, имя файла, название рендера. */
  title: 200,
  /** Ссылка на внешнее место. */
  url: 2000,
  /** Примечание к оплате, к отзыву счёта, причина отказа. */
  line: 1000,
  /** Комментарий, конфликт, решение арбитра, сообщение заказчика. */
  note: 4000,
  /** Постановка задачи: её пишет бюро, и она бывает длинной. */
  spec: 8000,
  /**
   * Таблица базы специалистов на импорт.
   *
   * Мерка другая: это не текст, который пишут руками, а файл, который
   * вставляют. Двух мегабайт хватает на десятки тысяч строк — больше похоже
   * не на базу бюро, а на промах.
   */
  csv: 2 * 1024 * 1024,
} as const

export class TooMuchText extends Error {
  constructor(readonly max: number) {
    super(
      `That is longer than this field takes (${max} characters). Shorten it, or attach the long version as a file.`,
    )
    this.name = 'TooMuchText'
  }
}

/**
 * Текст из формы: снять пробелы по краям и не пустить длиннее потолка.
 *
 * Считаются знаки, а не байты. Байты были бы честнее по расходу, но человек
 * видит перед собой знаки, и отказ «слишком длинно» по невидимой мерке
 * невозможно исполнить: одно и то же поле принимало бы разный текст в
 * зависимости от языка, на котором его написали.
 */
export function bounded(value: string, max: number): string {
  const text = value.trim()

  if (text.length > max) throw new TooMuchText(max)

  return text
}
