/**
 * Правовая сторона продукта: кто мы, по какому праву работаем, с какой версией
 * документов человек согласился.
 *
 * Реквизиты берутся из окружения, а не вписаны в разметку. Причина не в
 * гибкости: регистрационные данные меняются (адрес, счёт, номер в реестре), и
 * каждое такое изменение не должно быть правкой кода с выкладкой. Пока их нет,
 * страницы честно говорят, что реквизиты не заполнены, — это лучше, чем
 * правдоподобный вымышленный номер в документе, который человек подписывает.
 *
 * Отдельно про версию. Согласие с документом, который потом молча изменили, —
 * это не согласие. Поэтому вместе с отметкой времени хранится версия, и
 * менять её обязательно при каждой правке текста: по паре «когда и с чем»
 * восстанавливается, на что именно человек соглашался.
 */

/**
 * Версия правовых документов.
 *
 * Дата, а не номер: спорить будут о том, что было написано в конкретный день.
 * Меняется при любой правке смысла оферты или политики — вместе с самим
 * текстом, в одном коммите.
 */
export const LEGAL_VERSION = '2026-08-29'

/**
 * Применимое право.
 *
 * Юридическое лицо зарегистрировано в Черногории, и договор идёт по
 * черногорскому праву — независимо от того, откуда заказчик. Это не то же
 * самое, что продуктовая граница (п.5): предложить услугу мы можем кому
 * угодно, а выпустить разрешительную документацию — только там, где у команды
 * есть право подписи. Первое решает договор, второе — физика.
 */
export const GOVERNING_LAW = 'Черногория'

export type CompanyDetails = {
  /** Полное наименование юридического лица. */
  name: string
  /** Регистрационный номер в реестре. */
  registration: string
  /** Налоговый номер (PIB). */
  taxId: string
  /** Юридический адрес. */
  address: string
  /** Адрес для правовых обращений и вопросов по данным. */
  email: string
  /** Банковские реквизиты для оплаты счетов. */
  bank: string
}

/** Ничего не заполнено — так выглядит честное «реквизитов пока нет». */
const UNSET = ''

export function company(env: Record<string, string | undefined> = process.env): CompanyDetails {
  return {
    name: env.BUREAU_LEGAL_NAME?.trim() || UNSET,
    registration: env.BUREAU_LEGAL_REGISTRATION?.trim() || UNSET,
    taxId: env.BUREAU_LEGAL_TAX_ID?.trim() || UNSET,
    address: env.BUREAU_LEGAL_ADDRESS?.trim() || UNSET,
    email: env.BUREAU_LEGAL_EMAIL?.trim() || UNSET,
    bank: env.BUREAU_LEGAL_BANK?.trim() || UNSET,
  }
}

/**
 * Заполнены ли реквизиты настолько, чтобы оферта была офертой.
 *
 * Без наименования и регистрационного номера договор не с кем заключать, а без
 * адреса для обращений человеку некуда написать про свои данные. Банковские
 * реквизиты сюда не входят: без них нельзя выставить счёт, но можно принять
 * бриф, и это разные степени готовности.
 */
export function isIdentified(details: CompanyDetails = company()): boolean {
  return Boolean(details.name && details.registration && details.address && details.email)
}

/** Можно ли выставлять счёт: платить некуда, если банковские данные пусты. */
export function canInvoice(details: CompanyDetails = company()): boolean {
  return isIdentified(details) && Boolean(details.bank)
}
