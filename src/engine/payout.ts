/**
 * Что бюро должно за работу (концепт, п.14).
 *
 * Существует потому, что у бюро была только одна сторона денег. Цена стадии
 * считалась движком и объяснялась заказчику до цифры; расход не считался
 * нигде. Концепт называет гонорар один раз — «с гонорара специалиста комиссия
 * не берётся», — и этого хватает, чтобы понять: гонорар есть. В продукте его
 * не было ни полем, ни записью, поэтому валовая маржа не считалась не из-за
 * недостающего экрана, а из-за недостающего слагаемого.
 *
 * Форма ставки выбрана и это решение, а не умолчание: плата назначается за
 * дисциплину на стадии, а не за тикет. Тикеты внутри стадии — это то, как
 * реле разложило работу, и платить по их числу значило бы платить за
 * разбиение, а не за работу; при другом плане тикетов та же работа стоила бы
 * другое.
 *
 * Названное число при этом одно, а не таблица по площадям: его называют из
 * опыта — «конструктор за стадию разрешения обходится во столько», — и именно
 * в таком виде его знает тот, кто платил его руками. Но названо оно про
 * объект обычного размера и на конкретном проекте пересчитывается по площади
 * (`feeFactor`). Одно число, годное и для виллы в 250 м², и для квартала в
 * три тысячи, существовать не может: работа над разделом растёт с объектом.
 * Прежняя плоская сумма означала ровно это — и на маленьком объекте съедала
 * всю цену стадии, а на большом обесценивала работу.
 *
 * Ставки здесь не зашиты. В `pricing.ts` начальные цифры стоят намеренно:
 * заказчику нужно назвать цену до того, как накопится статистика. Здесь
 * наоборот — выдуманная ставка означает выдуманную маржу, а маржа это то, по
 * чему решают, жив ли бизнес. Не заданная ставка возвращает `null`, и все,
 * кто выше, обязаны показать «не задано», а не ноль: ноль читается как
 * «бесплатно», то есть как прибыль, которой нет.
 */

import { CURRENCY } from './pricing'
import type { Discipline, DocStage } from './taxonomy'

export { CURRENCY }

/** Ставка за дисциплину на стадии. Полный набор бюро задаёт само. */
export type PayoutRate = {
  discipline: Discipline
  stage: DocStage
  /** Сумма в единицах валюты, целыми. */
  amount: number
}

/**
 * Площадь, для которой названа ставка.
 *
 * Ставка — одно число, и в этом её смысл: её называют из опыта, а не выводят
 * из формулы. Но одно число не может быть верным и для виллы в 250 м², и для
 * квартала в три тысячи: работа над разделом растёт с объектом, а плата не
 * росла бы вовсе. Поэтому названное число привязано к объекту обычного
 * размера, а на конкретном проекте пересчитывается.
 *
 * Четыреста метров — середина основного размерного диапазона таксономии
 * (`250_1000`), то есть тот дом, о котором человек и думает, когда называет
 * цену раздела.
 */
export const FEE_REFERENCE_SQM = 400

/**
 * Пределы пересчёта.
 *
 * Снизу — потому что половина работы над разделом не зависит от площади вовсе:
 * посадка, согласование решения, выпуск. Ставка, падающая пропорционально до
 * нуля, на маленьком объекте означала бы отказ людей от работы, а не дешёвый
 * проект.
 *
 * Сверху — потому что за пределом множитель перестаёт описывать работу: на
 * объекте втрое больше обычного раздел ведёт не один человек, и это другой
 * разговор, а не другая сумма.
 */
const FEE_FACTOR_MIN = 0.6
const FEE_FACTOR_MAX = 3

/** Во сколько раз объект отличается от обычного, в пределах разумного. */
export function feeFactor(areaSqm: number): number {
  const raw = areaSqm / FEE_REFERENCE_SQM
  return Math.min(FEE_FACTOR_MAX, Math.max(FEE_FACTOR_MIN, raw))
}

/**
 * Что причитается за дисциплину на стадии на объекте этой площади.
 *
 * `null` остаётся `null`: незаданная ставка не становится нулём от того, что
 * её умножили.
 */
export function feeFor(
  rates: PayoutRate[],
  discipline: Discipline,
  stage: DocStage,
  areaSqm: number,
): number | null {
  const base = rateFor(rates, discipline, stage)
  if (base === null) return null
  return Math.round(base * feeFactor(areaSqm))
}

/** Ключ ставки в виде строки: пары «дисциплина + стадия» ищутся часто. */
function keyOf(discipline: Discipline, stage: DocStage): string {
  return `${discipline}:${stage}`
}

/**
 * Сколько бюро должно за одну дисциплину на одной стадии.
 *
 * `null` — «ставка не задана», и это не то же самое, что ноль. Ноль означал бы
 * бесплатную работу, то есть маржу, равную всей цене стадии.
 */
export function rateFor(
  rates: PayoutRate[],
  discipline: Discipline,
  stage: DocStage,
): number | null {
  const found = rates.find((r) => keyOf(r.discipline, r.stage) === keyOf(discipline, stage))
  return found ? found.amount : null
}

export type Owed = {
  /** Сумма по тому, что известно. */
  known: number
  /** Сколько обязательств осталось без ставки. */
  unknown: number
}

/** Складывает обязательства, не смешивая известное с незаданным. */
export function owed(amounts: (number | null)[]): Owed {
  let known = 0
  let unknown = 0

  for (const amount of amounts) {
    if (amount === null) unknown += 1
    else known += amount
  }

  return { known, unknown }
}

export type Margin =
  | {
      known: true
      /** Выручка минус расход. Может быть отрицательной — это тоже ответ. */
      amount: number
      /** Доля маржи в выручке, 0…1. При нулевой выручке — `null`. */
      share: number | null
    }
  | {
      known: false
      /** Сколько обязательств не имеют ставки. */
      missing: number
    }

/**
 * Валовая маржа проекта.
 *
 * Считается только когда известны все обязательства. Посчитанная по части —
 * это завышенная маржа: недостающие ставки всегда со стороны расхода, и
 * пропуск одной делает бизнес прибыльнее, чем он есть. Число, ошибающееся
 * всегда в одну сторону, хуже отсутствия числа: по нему принимают решения.
 */
export function margin(charged: number, obligations: Owed): Margin {
  if (obligations.unknown > 0) return { known: false, missing: obligations.unknown }

  const amount = charged - obligations.known
  return { known: true, amount, share: charged === 0 ? null : amount / charged }
}
